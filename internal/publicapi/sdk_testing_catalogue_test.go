// sdkTestingCataloguePath is the catalogue `@kaana.ai/sdk/testing` serves:
// GET /v1/models for Kaana's voice models, as this build renders it.
const sdkTestingCataloguePath = "../../packages/sdk/src/testing/catalogue.generated.ts"

// voiceDeployments are the voice models the fake serves, each as the
// publisher states it for its slug (publisher.StatedObservation).
var voiceDeployments = []struct {
	provider  contract.ProviderSlug
	protocol  string
	reference contract.ModelReference
	upstream  string
}{
	{"xai-realtime", providerconfig.ProtocolXAIRealtime, "x-ai/grok-voice-3.0@observed-2026-10-16", "grok-voice-3.0"},
	{"xai", providerconfig.ProtocolOpenAICompatible, "x-ai/grok-voice-transcribe-2.0@observed-2026-10-16", "grok-voice-transcribe-2.0"},
	{"groq", providerconfig.ProtocolOpenAICompatible, "openai/whisper-large-v3-turbo@observed-2026-10-16", "whisper-large-v3-turbo"},
	{"xai", providerconfig.ProtocolOpenAICompatible, "x-ai/text-to-speech@observed-2026-09-24", "tts"},
}

// TestTheSDKTestingCatalogueIsWhatKaanaServes holds the fake's catalogue to
// what this build serves for the same models: the declared file rendered with
// the publisher's own statements. A change to either fails here until the
// fixture is regenerated (KAANA_UPDATE_SDK_TESTING_CATALOGUE=1), so a client
// tested against the fake is tested against what Kaana publishes.
func TestTheSDKTestingCatalogueIsWhatKaanaServes(t *testing.T) {
	raw, err := os.ReadFile("../../configs/public-catalogue.json")
	if err != nil {
		t.Fatal(err)
	}
	catalogue, err := ParsePublicCatalogue(raw)
	if err != nil {
		t.Fatal(err)
	}
	deployments := make([]map[string]any, 0, len(voiceDeployments))
	for index, deployment := range voiceDeployments {
		entry := map[string]any{
			"deploymentId": "dep_voice_" + string(rune('a'+index)), "provider": deployment.provider,
			"modelReference": deployment.reference, "upstreamModelId": deployment.upstream, "current": true,
		}
		if observed := publisher.StatedObservation(deployment.provider, deployment.protocol, deployment.upstream); observed != nil {
			entry["observed"] = observed
		}
		deployments = append(deployments, entry)
	}
	document, err := json.Marshal(map[string]any{"snapshotId": "snap_sdk_testing", "issuedAt": contract.NewTimestamp(time.Now()), "deployments": deployments})
	if err != nil {
		t.Fatal(err)
	}
	current, err := inventory.Parse(document, time.Hour)
	if err != nil {
		t.Fatal(err)
	}
	var models []json.RawMessage
	for _, entry := range current.Catalogue() {
		declared, known := catalogue.models[entry.Model]
		if !known {
			t.Fatalf("%s is not declared in configs/public-catalogue.json", entry.Model)
		}
		_, revision, _ := strings.Cut(string(entry.Reference), "@")
		rendered, err := declared.render(entry, []string{revision})
		if err != nil {
			t.Fatal(err)
		}
		models = append(models, rendered)
	}
	var data bytes.Buffer
	if err := json.Indent(&data, mustJSON(t, models), "", "  "); err != nil {
		t.Fatal(err)
	}
	want := "// Generated by internal/publicapi TestTheSDKTestingCatalogueIsWhatKaanaServes; do not edit.\n" +
		"// GET /v1/models for Kaana's voice models, as Kaana renders them from configs/public-catalogue.json\n" +
		"// and the publisher's statements. Regenerate with KAANA_UPDATE_SDK_TESTING_CATALOGUE=1 go test ./internal/publicapi.\n\n" +
		"export const voiceCatalogueSnapshot: readonly unknown[] = " + data.String() + ";\n"
	if os.Getenv("KAANA_UPDATE_SDK_TESTING_CATALOGUE") == "1" {
		if err := os.WriteFile(sdkTestingCataloguePath, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(sdkTestingCataloguePath)
	if err != nil || string(got) != want {
		t.Fatalf("%s is not what Kaana serves for its voice models; regenerate it with KAANA_UPDATE_SDK_TESTING_CATALOGUE=1 go test ./internal/publicapi -run TestTheSDKTestingCatalogueIsWhatKaanaServes", sdkTestingCataloguePath)
	}
}

func mustJSON(t *testing.T, value any) []byte {
	t.Helper()
	encoded, err := json.Marshal(value)
	if err != nil {
		t.Fatal(err)
	}
	return encoded
}
